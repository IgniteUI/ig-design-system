// The document the guide and the token showcase share: the head, the top bar, the stylesheet and the client script.
import fs from "node:fs";
import { fromRoot } from "./paths.ts";
import type { Tokens } from "./types.ts";

// The stylesheet of both pages; {{breakpoint-lg}} stands for the breakpoint-lg token.
const PAGE_CSS = fs.readFileSync(fromRoot("src/showcase.css"), "utf8");
// The script both pages run: the theme and type set buttons, copying, the dials, the filter.
const CLIENT_SCRIPT = fs.readFileSync(
  fromRoot("src/showcase.client.js"),
  "utf8",
);

// The Infragistics logo for the light and for the dark theme, as the marketing site ships them.
const LOGOS = (["light", "dark"] as const)
  .map((theme) => {
    const file = theme === "dark" ? "ig-logo-dark.svg" : "ig-logo.svg";
    const svg = fs.readFileSync(fromRoot("src/assets", file), "utf8");
    const start = svg.indexOf("<svg");
    if (start < 0)
      throw new Error(
        `src/assets/${file} holds no <svg> element. Copy the logo again from the marketing site.`,
      );
    // Drops the XML prolog and the id both files share, and hides the drawing from assistive technology.
    return svg
      .slice(start)
      .replace(/\sid="[^"]*"/, "")
      .replace("<svg", `<svg class="logo logo-${theme}" aria-hidden="true"`)
      .trim();
  })
  .join("\n    ");

/** The pages of the site, in the order the top bar lists them. */
export const PAGES = [
  { id: "guide", href: "index.html", title: "Guide" },
  { id: "tokens", href: "showcase.html", title: "Tokens" },
] as const;
export type PageId = (typeof PAGES)[number]["id"];

export const esc = (s: string) =>
  s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

type Page = {
  /** The page in PAGES this document is. */
  current: PageId;
  title: string;
  /** The source file named in the generated-file comment. */
  source: string;
  /** Styles added after the shared stylesheet. */
  css?: string;
  /** Markup between the page links and the theme button. */
  bar?: string;
  /** Buttons added after the theme button. */
  switches?: string;
  body: string;
};

/** Wraps a page body in the shared document. */
export const page = (T: Tokens, p: Page) => {
  const lg =
    T.breakpoint.tokens.find((t) => t.name === "breakpoint-lg")?.value ??
    "1024px";
  const css = (PAGE_CSS + (p.css ?? "")).replaceAll("{{breakpoint-lg}}", lg);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(p.title)}</title>
<!-- Generated by ${p.source} from dist/tokens.json. Do not edit by hand. -->
<script>
// Applies the stored theme before the first paint; with none stored the page follows the system.
(function () {
  var stored = null;
  try { stored = localStorage.getItem("igd-showcase-theme"); } catch (e) {}
  var dark = stored ? stored === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
  document.documentElement.setAttribute("data-theme", dark ? "dark" : "light");
})();
</script>
<link rel="stylesheet" href="../dist/fonts.css">
<link rel="stylesheet" href="../dist/tokens.css">
<link rel="stylesheet" href="../dist/theme.css">
<link rel="stylesheet" href="../dist/base.css">
<style>
${css}</style>
</head>
<body>
<header class="top">
  <a class="brand" href="index.html" aria-label="Infragistics design system">
    ${LOGOS}
    <span>Design system</span>
  </a>
  <nav class="pages" aria-label="Pages">
    ${PAGES.map((x) => `<a href="${x.href}"${x.id === p.current ? ' aria-current="page"' : ""}>${x.title}</a>`).join("\n    ")}
  </nav>
  ${p.bar ?? '<span class="find"></span>'}
  <div class="switches">
    <button type="button" id="theme" aria-pressed="false">Dark theme</button>
    ${p.switches ?? ""}
  </div>
</header>
${p.body}
<p class="toast" id="toast" role="status"></p>
<script>
${CLIENT_SCRIPT}</script>
</body>
</html>
`;
};
