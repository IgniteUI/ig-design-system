// Writes llms.txt, the rules for code that uses the tokens, and llms-full.txt, every token.
// Usage: node src/llms.ts <tokens.json> <package.json> <llms.txt> <llms-full.txt> <tokens.css> <theme.css>
import fs from "node:fs";
import { CHECKS, NOT_CHECKED } from "../checks/rules.ts";
import { isMain } from "./main.ts";
import { cssVar } from "./namespace.ts";
import { EMPHASIS, NOT_USED, PROPERTIES, STATES } from "./naming.ts";
import { fromRoot } from "./paths.ts";
import { RULES } from "./rules.ts";
import {
  type Tokens as FullTokens,
  TOKEN_FAMILIES,
  type Token,
  type TokenFamily,
  type TokenFamilyName,
} from "./types.ts";
import { checkCommand, DIALS, installCommand, STYLESHEETS } from "./usage.ts";

export type Tokens = Record<string, unknown>;

/** The example component llms.txt quotes: its page and its stylesheet. */
export const EXAMPLE = "docs/examples/card.html";
export const EXAMPLE_CSS = "docs/examples/card.css";

/** The example component as llms.txt quotes it. */
export type Example = { html: string; css: string };

const code = (s: string) => `\`${s}\``;
const sentence = (items: readonly string[]) =>
  items.length < 2
    ? items.join("")
    : `${items.slice(0, -1).join(", ")} and ${items.at(-1)}`;

// The heading each token family gets.
const FAMILIES: Record<TokenFamilyName, string> = {
  color: "Colour",
  spacing: "Spacing",
  radius: "Radius",
  size: "Size",
  shadow: "Shadow",
  opacity: "Opacity",
  weight: "Font weight",
  gradient: "Gradient",
  breakpoint: "Breakpoint",
  zIndex: "Layer",
};

const families = (tokens: Tokens) =>
  TOKEN_FAMILIES.map((key) => {
    const family = tokens[key] as TokenFamily | undefined;
    if (!family?.tokens)
      throw new Error(
        `llms: tokens.json has no "${key}" family. Update FAMILIES in src/llms.ts to match it.`,
      );
    return { key, title: FAMILIES[key], family };
  });

const isEngine = (t: Token) => t.name.startsWith("ig-");

/** The short file: what the package is, the rules for code that uses it, and where to read more. */
export const llmsTxt = (
  tokens: Tokens,
  pkg: { name: string; description: string },
  example?: Example,
) => {
  const roles = (tokens.type as FullTokens["type"] | undefined)?.groups.flatMap(
    (g) => g.styles,
  ).length;
  const rules = RULES.map((r, i) => {
    const check = CHECKS.find((c) => c.id === r.check);
    const reported = check
      ? `The check reports it as \`${check.id}\`${check.strict ? ", only with `--strict`" : ""}.`
      : "The check does not report it.";
    return `${i + 1}. **${r.title}** ${r.why} Write ${code(r.good)}, not ${code(r.bad)}. ${reported}`;
  }).join("\n");
  const counts = families(tokens)
    .map(({ title, family }) => {
      const own = family.tokens.filter((t) => !isEngine(t)).length;
      const engine = family.tokens.length - own;
      return `- ${title}: ${own} tokens${engine ? `, plus ${engine} engine palette steps a site does not read` : ""}`;
    })
    .join("\n");
  return `# ${pkg.name}

> ${pkg.description} This file is generated by \`src/llms.ts\` on every build; do not edit it.

One design system for the Infragistics sites. It ships CSS custom properties and the checks that keep a site on them. It has no components and no JavaScript a page loads.

## Using it in a site

\`\`\`sh
${installCommand(pkg.name)}
\`\`\`

Load the stylesheets in this order, before the site's own styles:

${STYLESHEETS.map((s, i) => `${i + 1}. \`${pkg.name}/${s.file}\` — ${s.optional ? "optional. " : ""}${s.note}`).join("\n")}

\`\`\`css
${STYLESHEETS.map((s) => `@import '${pkg.name}/${s.file}';`).join("\n")}
\`\`\`

A documentation site puts \`data-igd-type="docs"\` on \`<html>\` for the smaller type set. \`data-theme="dark"\` selects the dark variant.

## Rules for code that uses the tokens

${rules}

Also:

- A custom property is \`--igd-*\` when the design system defines it and \`--ig-*\` only when the \`igniteui-theming\` engine emits that exact name.
- Padding uses \`--igd-space-inset-*\`, vertical margins \`--igd-space-stack-*\`, gaps and inline margins \`--igd-space-gap-*\`.
- Hover, active and focus colours are derived from their base token. Override the base on a scope and the states follow.
- A component puts \`data-ig-scope\` on its root element, so a dial (${sentence(DIALS.map(code))}) set on any ancestor reaches it. Set a dial on the root or on a \`data-ig-scope\` element.
- When no token fits, do not invent a value that looks like one. Say which token is missing.
- Do not add a fallback to a token read, \`var(--igd-color-foreground-subtle, #333)\`: the check skips a \`var()\` with a fallback, so a typo in its name goes unreported.

## Checking a site

Run \`${checkCommand(pkg.name)}\`. It exits with 1 when it finds:

${CHECKS.map((c) => `- \`${c.id}\`: ${c.reports}${c.strict ? " (only with `--strict`)" : ""}`).join("\n")}

\`--ignore <text>\` skips every path that contains the text. The check does not report:

${NOT_CHECKED.map((n) => `- ${n.text}`).join("\n")}

## How to read a colour name

\`color-{property}-{job}-{emphasis}-{state}\`, read as a sentence: \`color-foreground-link-hover\` is the foreground colour of a link, on hover. A component's own colour reads \`{component}-{part}-{property}-{state}\`: \`badge-new-foreground\`.

${PROPERTIES.map((p) => `- \`${p.word}\`: ${p.means}`).join("\n")}

Emphasis: ${EMPHASIS.map((e) => `\`${e.word}\` (${e.means})`).join(", ")}. A state comes last: ${STATES.map((s) => `\`${s.word}\` (${s.means})`).join(", ")}. A colour on a fill says so: \`color-foreground-on-action\` is the label on \`color-background-action\`. A name never uses ${Object.entries(
    NOT_USED,
  )
    .map(([w, use]) => `\`${w}\` (it says ${use})`)
    .join(", ")}.

## What is in it

${counts}
- Type: ${roles} roles (\`--igd-type-<role>-font-family\`, \`-font-size\`, \`-font-weight\`, \`-line-height\`, \`-letter-spacing\`, \`-text-transform\`) and the classes \`.igd-type-<role>\`
${example ? `\n## Writing a component\n\nThe same in every framework and every repository: plain HTML, Astro, React, Angular, a web component. It applies to every component built on the design system, not only to Ignite UI components.\n\n1. Put \`data-ig-scope\` on the root element of the component. The design system calculates its tokens on the root of the page and on each \`data-ig-scope\` element. With the attribute, a dial set on any ancestor reaches the component, as it reaches an Ignite UI component. Without it, the component keeps the values of the page.\n2. A component with shadow DOM puts the attribute on its host element. The stylesheet of the page does not reach inside a shadow root.\n3. Style the component with the rules above: spacing roles, semantic colours, type classes, typed widths and heights.\n4. Do not set a dial or a spacing, size or radius step inside the component. The page sets dials.\n\n\`${EXAMPLE}\` is a card written this way, in plain HTML and CSS, with its rules in \`${EXAMPLE_CSS}\`. Its second card sits in a section that sets two dials.\n\n\`\`\`css\n${example.css.trim()}\n\`\`\`\n\n\`\`\`html\n${example.html.trim()}\n\`\`\`\n` : ""}
## Read next

- [llms-full.txt](llms-full.txt): every token with its value and what it is for
- [README.md](README.md): the files, the token tiers, theming, the checks
- [CHANGELOG.md](CHANGELOG.md): what each version changes
- [dist/tokens.json](dist/tokens.json): the tokens as data, imported as \`${pkg.name}/tokens.json\`
- [docs/examples/card.html](docs/examples/card.html) and [docs/examples/card.css](docs/examples/card.css): a component written to the rules, in plain HTML and CSS
- [docs/ADOPTING.md](docs/ADOPTING.md): moving an existing site onto the design system
- [docs/MIGRATION.md](docs/MIGRATION.md): old token names and their replacements
`;
};

/** The `--igd-*` properties a stylesheet declares that tokens.json does not list, with their first value. Type role properties are left out. */
export const stylesheetOnly = (tokens: Tokens, css: string) => {
  const listed = new Set(
    families(tokens).flatMap(({ family }) =>
      family.tokens.map((t) => cssVar(t.name)),
    ),
  );
  const found = new Map<string, string>();
  for (const [, name, value] of css.matchAll(
    /(?<![\w-])(--igd-[\w-]+)\s*:\s*([^;]+);/g,
  ))
    if (
      !listed.has(name) &&
      !name.startsWith("--igd-type-") &&
      !found.has(name)
    )
      found.set(name, value.trim().replace(/\s+/g, " "));
  return [...found];
};

/** The long file: every token a site may read, with its value and usage. Engine palette steps are left out. */
export const llmsFullTxt = (
  tokens: Tokens,
  pkg: { name: string },
  css = "",
) => {
  const others = stylesheetOnly(tokens, css)
    .map(([name, value]) => `- \`${name}\`: \`${value}\``)
    .join("\n");
  const sections = families(tokens)
    .map(({ title, family }) => {
      const own = family.tokens.filter((t) => !isEngine(t));
      const lines = own
        .map((t) => `- \`${cssVar(t.name)}\`: \`${t.value}\`. ${t.usage}`)
        .join("\n");
      return `## ${title}\n\n${family.note ? `${family.note}\n\n` : ""}${lines}`;
    })
    .join("\n\n");
  const type = tokens.type as FullTokens["type"];
  const docs = new Map((type.sets.docs ?? []).map((s) => [s.name, s.fontSize]));
  const roles = type.groups
    .flatMap((g) => g.styles)
    .map(
      (s) =>
        `- \`${s.name.replace(/^type-/, "")}\`: ${s.fontSize}${s.fontSizeMin ? `, fluid from ${s.fontSizeMin}` : ""}, line height ${s.lineHeight}, weight ${s.fontWeight}${docs.has(s.name) ? `; ${docs.get(s.name)} in the docs set` : ""}. ${s.usage}`,
    )
    .join("\n");
  return `# ${pkg.name}: every token

> Generated by \`src/llms.ts\` from \`dist/tokens.json\` and the two stylesheets on every build; do not edit it. The values are the defaults in the light variant. Start with [llms.txt](llms.txt) for the rules.

${sections}

## Type roles

Each role has \`--igd-type-<role>-font-family\`, \`-font-size\`, \`-font-weight\`, \`-line-height\`, \`-letter-spacing\` and \`-text-transform\`, and the class \`.igd-type-<role>\`.

${roles}
${others ? `\n## Declared in the stylesheets only\n\nCustom properties of \`tokens.css\` and \`theme.css\` that have no entry in \`tokens.json\`, with their first value.\n\n${others}\n` : ""}`;
};

if (isMain(import.meta.url)) {
  const [tokensFile, pkgFile, short, full, ...cssFiles] = process.argv.slice(2);
  const tokens = JSON.parse(fs.readFileSync(tokensFile, "utf8"));
  const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
  fs.writeFileSync(
    short,
    llmsTxt(tokens, pkg, {
      html: fs.readFileSync(fromRoot(EXAMPLE), "utf8"),
      css: fs.readFileSync(fromRoot(EXAMPLE_CSS), "utf8"),
    }),
  );
  fs.writeFileSync(
    full,
    llmsFullTxt(
      tokens,
      pkg,
      cssFiles.map((f) => fs.readFileSync(f, "utf8")).join("\n"),
    ),
  );
  console.log(`llms: wrote ${short} and ${full}`);
}
